"""把 148 嫌疑带的弱档判读结果落台账:真漏线(竖)/文字错数/非漏线/不明。
判读=助手视觉判读(弱档),依据 runs/tmp/疑漏带核实_20261005/包01-13.png。
真漏线A=sub_row实锤(线已检出但被降级); 真漏线B=原图有线但无任何候选段(约束2禁造线,登记)。"""
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from src.core import paths

# 真漏线A: 判读见包01-13, 两行数字+两行描述, 带内 sub_row 即那条线
A = {
    ("1015", 30), ("1016", 58), ("1016", 135), ("1018", 104),
    ("1020", 73), ("1020", 82), ("1020", 109), ("1020", 130), ("1020", 144),
    ("1020", 151), ("1024", 143), ("1024", 145), ("1024", 146),
    ("1027", 80), ("1027", 87), ("1028", 98), ("1028", 150),
    ("1035", 156), ("1040", 57), ("1040", 88), ("1042", 59),
    ("1044", 8), ("1044", 18),
}
# 真漏线B: 原图可见线,带内无候选段(不可造线,登记)
B = {("1018", 91), ("1020", 26), ("1027", 77), ("1027", 98), ("1035", 36),
     ("1037", 78), ("1044", 73)}
# 文字错数(算术+裁片双定位, 待原图放大复核后改)
T = {
    ("1037", 19): "深度23394.0→233.94(小数点丢失)",
    ("1037", 24): "深度25108.0→251.08(小数点丢失)",
    ("1042", 53): "深度25046.0→250.46(小数点丢失)",
    ("1042", 60): "深度28200.0→282.00(小数点丢失)",
    ("1031", 48): "深度235.77→265.77(3/6误读,265.77+2.83=268.60✓)",
    ("1033", 45): "深度329.07→349.07(2/4误读,349.07+0.50=349.57✓)",
    ("1034", 118): "深度207.01→297.01(0/9误读,297.01+3.41=300.42✓)",
}
# 疑似真漏线(裁片不完整,待复核)
Q = {("1017", 28), ("1027", 12), ("1035", 165), ("1038", 60), ("1020", 89)}

rows = list(csv.reader(open(paths.RUNS_DIR / "tmp" / "疑漏带归因_20261005.csv",
                            encoding="utf-8-sig")))[1:]
out = []
for r in rows:
    key = (r[0], int(r[1]))
    if key in A:
        cls = "真漏线A(sub实锤)"
    elif key in B:
        cls = "真漏线B(无候选,登记)"
    elif key in T:
        cls = f"文字错数: {T[key]}"
    elif key in Q:
        cls = "疑似真漏线(待复核)"
    elif "两数同格" in r[2] and r[2].split("+") == ["两数同格"]:
        cls = "横类(列界/裁片,单带)"
    else:
        cls = "非漏线(单带,数据关联或原图如此)"
    out.append(r + [cls])
with open(paths.RUNS_DIR / "tmp" / "疑漏带判读_20261005.csv", "w", newline="",
          encoding="utf-8-sig") as fp:
    w = csv.writer(fp)
    w.writerow(["图号", "xlsx行", "信号", "带y0", "带y1", "带内sub数", "sub y样例",
                "带内off数", "判读(助手弱档)"])
    w.writerows(out)
from collections import Counter
c = Counter(o[-1].split("(")[0].split(":")[0] for o in out)
print("判读分布:", dict(c))
for k in ("真漏线A", "真漏线B"):
    n = sum(1 for o in out if o[-1].startswith(k))
    print(k, n)
