COLNAME = {1: "煤层标志层号", 2: "深度", 3: "层厚"}

BACKUP.mkdir(parents=True, exist_ok=True)
stems = sorted({f[0] for f in FIXES})
missing = []
for s in stems:
    src = B / f"钻孔柱状图{s}_还原.xlsx"
    dst = BACKUP / f"钻孔柱状图{s}_还原.xlsx"
    if not src.exists():
        missing.append(s)
        continue
    if not dst.exists():
        shutil.copy2(src, dst)

ledger = []
for s, r, ci, old, new, why in FIXES:
    fp = B / f"钻孔柱状图{s}_还原.xlsx"
    if not fp.exists():
        print(f"[缺] {s} 尚未出表,留待重跑")
        ledger.append([s, r, COLNAME[ci], old, new, why, "缺文件,待补"])
        continue
    wb = load_workbook(fp)
    ws = wb.active
    vals = list(ws.iter_rows(values_only=True))
    cell = vals[r - 1][ci]
    if cell is not None and abs(float(str(cell)) - float(new)) < 1e-9:
        print(f"[=] {s} r{r} {COLNAME[ci]} 已是新值 {new}")
        ledger.append([s, r, COLNAME[ci], old, new, why, "已是新值"])
        continue
    if float(str(cell)) != float(old):
        print(f"[!] {s} r{r} 现值{cell!r} ≠ 预期旧值{old},跳过")
        ledger.append([s, r, COLNAME[ci], cell, new, why, "跳过:现值不符"])
        continue
    ws.cell(row=r, column=ci + 1, value=float(new))
    wb.save(fp)
    print(f"[ok] {s} r{r} {COLNAME[ci]}: {old} → {new}")
    ledger.append([s, r, COLNAME[ci], old, new, why, "已改"])

out = B / "错数更正账_20261005.csv"
with open(out, "w", newline="", encoding="utf-8-sig") as f:
    w = csv.writer(f)
    w.writerow(["图号", "xlsx行", "列", "旧值", "新值", "依据", "处置"])
    w.writerows(ledger)
print(f"账本 {len(ledger)} 条 → {out}")

# 回读校验
